import fs from 'node:fs';
import path from 'node:path';
const appDir='android/app/src/main';
const manifest=path.join(appDir,'AndroidManifest.xml');
if(!fs.existsSync(manifest)) throw new Error('Android project missing. Run npx cap add android first.');
const testAppId='ca-app-pub-3940256099942544~3347511713';
const appId=process.env.ADMOB_APP_ID || testAppId;
if(!/^[0-9]{16}~[0-9]{10}$/.test(appId)) throw new Error('ADMOB_APP_ID format is invalid.');
const resDir=path.join(appDir,'res/values');fs.mkdirSync(resDir,{recursive:true});
const strings=path.join(resDir,'strings.xml');let xml=fs.existsSync(strings)?fs.readFileSync(strings,'utf8'):'<resources>\n</resources>\n';
const resource=`<string name="admob_app_id">${appId}</string>`;
if(/<string name="admob_app_id">[\s\S]*?<\/string>/.test(xml)) xml=xml.replace(/<string name="admob_app_id">[\s\S]*?<\/string>/,resource); else xml=xml.replace('</resources>',`    ${resource}\n</resources>`);
fs.writeFileSync(strings,xml);
let m=fs.readFileSync(manifest,'utf8');
if(!m.includes('com.android.vending.BILLING')) m=m.replace(/<manifest([^>]*)>/,`<manifest$1>\n    <uses-permission android:name="com.android.vending.BILLING" />`);
const meta='<meta-data android:name="com.google.android.gms.ads.APPLICATION_ID" android:value="@string/admob_app_id" />';
if(/<meta-data[^>]*android:name="com.google.android.gms.ads.APPLICATION_ID"[^>]*\/>/.test(m)) m=m.replace(/<meta-data[^>]*android:name="com.google.android.gms.ads.APPLICATION_ID"[^>]*\/>/,meta); else m=m.replace('</application>',`        ${meta}\n    </application>`);
fs.writeFileSync(manifest,m);
console.log(`Android manifest configured; AdMob app ID ${process.env.ADMOB_APP_ID?'provided via environment':'is Google test ID'}.`);
