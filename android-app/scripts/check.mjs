import fs from 'node:fs';
import path from 'node:path';
const config=fs.readFileSync('capacitor.config.ts','utf8');
const html=fs.readFileSync('web/index.html','utf8');
const module=fs.readFileSync('web/src/monetization.js','utf8');
if(html.includes('/DinoCrawler/')) throw new Error('GitHub Pages absolute asset paths remain');
if(html.includes('rel="manifest"')) throw new Error('Web manifest link should not ship inside the native app');
if(html.includes("serviceWorker.register('/DinoCrawler/sw.js')")) throw new Error('Hosted service worker remains');
if(!html.includes('btn-remove-ads')||!html.includes('btn-restore-purchases')) throw new Error('Accessible purchase controls missing');
if(!html.includes('role="status" aria-live="polite"')) throw new Error('Purchase status is not announced to screen readers');
if(!html.includes('showInterstitialAfterResultsExit')) throw new Error('Interstitial handoff missing');
if(!config.includes("webDir: 'www'")) throw new Error('Capacitor webDir must be www');
if(!config.includes('androidpending')) throw new Error('Temporary app ID marker missing');
for(const m of html.matchAll(/new Audio\(['"]audio\/([^'"]+)['"]\)/g)) if(!fs.existsSync(path.join('web/public/audio',m[1]))) throw new Error(`Missing audio ${m[1]}`);
if(!module.includes("VITE_USE_TEST_ADS !== 'false'")||!module.includes('isTesting: USE_TEST_ADS')) throw new Error('Ads must remain test-only until configured');
if(!module.includes("purchaseState === 'PURCHASED'") || !module.includes('isAcknowledged === true')) throw new Error('Purchase confirmation does not validate completed acknowledged transaction');
if(!module.includes('VITE_ADMOB_INTERSTITIAL_ID')) throw new Error('Production AdMob ID needs an explicit build-time setting');
if(!module.includes('dinoCrawler.removeAds')) throw new Error('Purchase recovery cache missing');
const pkg=JSON.parse(fs.readFileSync('package.json','utf8'));
for(const name of ['@capacitor-community/admob','@capgo/native-purchases','@capacitor/android','@capacitor/cli','vite']) if(!pkg.dependencies[name]&&!pkg.devDependencies[name]) throw new Error(`Missing ${name}`);
if(fs.existsSync('src-tauri')) throw new Error('Obsolete Tauri project remains');
console.log('Static Capacitor source checks passed; native build/device test not run.');
